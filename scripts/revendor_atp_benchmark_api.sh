#!/usr/bin/env bash
# Re-vendor contracts/atp-benchmark-api/v1 at a new producer commit.
#
# The pin is the ONE input. Everything written — the pruned openapi.json,
# PINNED.txt, manifest.json — is derived from the SHA on argv, so the
# guarantee is not "three literals agree with each other" but "the openapi
# bytes on disk are, byte for byte, a canonical pruning of the schema the
# named commit's eco app serves".
#
# Unlike the gate-catalog/actions vendors this adapts (which extract a file
# unchanged from git objects), this contract's surface — openapi.json — does
# not exist as a blob in atp-platform at all: it is generated by booting the
# eco app and calling its own `.openapi()`. So the source of truth is a
# checkout, not an object database, and provenance is "this checkout was at
# exactly this commit when the app ran", verified with `git rev-parse
# HEAD` in a throwaway worktree rather than a blob-hash comparison.
#
# Fixtures (contracts/atp-benchmark-api/v1/fixtures/*.json) are NOT
# regenerated here — they are consumer-maintained examples, carried over
# byte-for-byte from the previous vendored copy. See
# docs/revendor-atp-benchmark-api.md for the by-hand refresh step.
#
# The working copy is never touched until a fully verified candidate exists:
# generation happens in a staging directory beside it, and the swap is a
# same-filesystem rename with a restoring trap. A failure anywhere leaves
# the previous vendored copy exactly as it was.
#
# Usage:
#   scripts/revendor_atp_benchmark_api.sh <NEW_PIN> [--from <atp-platform-checkout>]
#
# Default --from: ../atp-platform. No network-fetch mode exists for this
# contract (unlike the git-object vendors) — atp-platform is always read as
# a local checkout, so --from names a path, never a remote.
#
# Exit: 0 ok · 1 usage · 2 source or commit unavailable ·
#       3 provenance mismatch · 4 manifest generation or read-back ·
#       5 internal failure (working copy left as it was found)
#       Any other nonzero status (127, 128, …) is an unexpected internal
#       failure; the trap below has still restored the tree.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DST="$REPO_ROOT/contracts/atp-benchmark-api/v1"
STAGING="$DST.staging"
PREV="$DST.prev"

die() { echo "revendor: $2" >&2; exit "$1"; }

NEW_PIN=""
FROM="../atp-platform"
while [ $# -gt 0 ]; do
  case "$1" in
    --from)
      [ $# -ge 2 ] || die 1 "--from needs a path"
      case "$2" in
        -*) die 1 "--from wants a path, not an option: $2" ;;
      esac
      FROM="$2"
      shift 2
      ;;
    -h | --help)
      # Print the header comment (lines 2..the line before `set -euo
      # pipefail`), bounded by a sentinel rather than a line number so the
      # printed table can never drift from the header it is quoting again.
      awk 'NR>1{if (/^set -euo pipefail/) exit; print}' "${BASH_SOURCE[0]}" >&2
      exit 0
      ;;
    -*) die 1 "unknown option: $1" ;;
    *)
      [ -z "$NEW_PIN" ] || die 1 "exactly one commit may be given"
      NEW_PIN="$1"
      shift
      ;;
  esac
done

[ -n "$NEW_PIN" ] || die 1 "usage: $(basename "$0") <NEW_PIN> [--from <atp-platform-checkout>]"
# A full 40-hex commit id only. A branch name or an abbreviation resolves
# perfectly well here and would then be written into the manifest as though
# it identified a commit for good.
[[ "$NEW_PIN" =~ ^[0-9a-f]{40}$ ]] || die 1 "not a full 40-hex commit id: $NEW_PIN"

FROM="$(cd "$FROM" 2>/dev/null && pwd)" || die 2 "--from path does not exist"
git -C "$FROM" rev-parse --git-dir > /dev/null 2>&1 ||
  die 2 "--from is not a git repository: $FROM"
git -C "$FROM" cat-file -e "$NEW_PIN^{commit}" 2> /dev/null ||
  die 2 "$NEW_PIN is not a commit in $FROM"

command -v python3 > /dev/null 2>&1 || die 4 "python3 not found on PATH"
command -v uv > /dev/null 2>&1 || die 2 "uv not found on PATH"

WORK="$(mktemp -d)" || die 5 "could not create a scratch directory"
TMP_WT="$WORK/atp-platform-at-pin"

cleanup() {
  local code=$?
  # Only ever remove a worktree we ourselves registered — never touch $FROM
  # itself, which is read-only reference (repo-boundaries).
  if [ -d "$TMP_WT" ]; then
    git -C "$FROM" worktree remove --force "$TMP_WT" 2> /dev/null || true
  fi
  rm -rf "$WORK" "$STAGING"
  # Died between the two renames: the working copy is in $PREV and $DST is
  # gone. Put it back — a failed re-vendor must leave the tree as it found it.
  if [ -d "$PREV" ]; then
    [ -e "$DST" ] || mv "$PREV" "$DST"
    rm -rf "$PREV"
  fi
  exit "$code"
}
trap cleanup EXIT

# Extract into a fresh staging directory, never over the top of the current
# copy: a schema upstream removed would otherwise survive as ours and be
# certified by the manifest we are about to generate.
rm -rf "$STAGING"
mkdir -p "$STAGING" "$STAGING/fixtures"

git -C "$FROM" worktree add --quiet --detach "$TMP_WT" "$NEW_PIN" ||
  die 2 "could not check out $NEW_PIN from $FROM into a worktree"

# The provenance check this contract can make: the worktree HEAD is exactly
# the commit we were given. (There is no blob to hash — openapi.json is
# generated, not extracted — so this replaces the two-directional
# file/blob comparison the git-object vendors use.)
CHECKED_OUT="$(git -C "$TMP_WT" rev-parse HEAD)" ||
  die 3 "could not read HEAD of the worktree checked out at $NEW_PIN"
[ "$CHECKED_OUT" = "$NEW_PIN" ] ||
  die 3 "worktree HEAD ($CHECKED_OUT) is not $NEW_PIN"

# ATP_SECRET_KEY: create_app()'s config load fails closed without one.
# Schema generation touches no database and no real secret, so a fixed,
# clearly-a-placeholder value is fine here — it never leaves this process.
#
# The schema is written straight to a file from inside the interpreter,
# not captured off stdout: atp's own logging setup (LOGGER_DUMP) writes
# informational lines to stdout too, which would otherwise interleave with
# the JSON and make it unparseable.
ATP_SERVER_PROFILE=eco ATP_SECRET_KEY="revendor-atp-benchmark-api-placeholder-key" \
  uv run --project "$TMP_WT" python - "$STAGING/openapi-full.json" << 'PY'
import json
import sys
from atp.dashboard.v2.factory import create_app

with open(sys.argv[1], "w") as fh:
    json.dump(create_app().openapi(), fh)
PY
python3 "$REPO_ROOT/scripts/prune_atp_openapi.py" \
  "$STAGING/openapi-full.json" "$STAGING/openapi.json"
rm "$STAGING/openapi-full.json"
git -C "$FROM" worktree remove --force "$TMP_WT"

# Fixtures are carried over from the existing vendored copy — they are
# consumer-maintained examples, not derived from the pin. See
# docs/revendor-atp-benchmark-api.md for the by-hand refresh step.
if [ -d "$DST/fixtures" ]; then
  cp "$DST"/fixtures/*.json "$STAGING/fixtures/" 2> /dev/null ||
    die 2 "could not carry over fixtures from $DST/fixtures"
fi

# The fixtures themselves are carried over by bytes above; the record of
# where those bytes came from (ORM-seeded vs. real endpoint capture, etc.)
# lives only in the previous PINNED.txt's "fixtures:" block and is not
# derivable from the pin, so it must be carried over too — otherwise a
# re-vendor silently drops the provenance note while keeping the fixture
# bytes it describes. No previous PINNED.txt (first bootstrap) means no
# block to carry, not an error.
FIXTURES_BLOCK=""
if [ -f "$DST/PINNED.txt" ]; then
  FIXTURES_BLOCK="$(python3 - "$DST/PINNED.txt" << 'PY'
import re
import sys

lines = open(sys.argv[1]).read().splitlines()
block: list[str] = []
in_block = False
for line in lines:
    if in_block and (line.startswith(" ") or line.startswith("\t")):
        block.append(line)
        continue
    in_block = re.match(r"^fixtures:", line) is not None
    if in_block:
        block.append(line)
print("\n".join(block))
PY
  )" || die 2 "could not read fixtures provenance from $DST/PINNED.txt"
fi

{
  printf 'source: atp-platform packages/atp-dashboard/atp/dashboard/v2/factory.py\n'
  printf '        (create_app().openapi(), ATP_SERVER_PROFILE=eco), pruned to the\n'
  printf '        GET paths dispatcher consumes (scripts/prune_atp_openapi.py)\n'
  printf 'commit: %s\n' "$NEW_PIN"
  printf 'vendored: %s\n' "$(date -u +%Y-%m-%d)"
  [ -z "$FIXTURES_BLOCK" ] || printf '%s\n' "$FIXTURES_BLOCK"
  cat << 'EOF'
note: pinned copy (repo-boundaries vendoring, ADR-ECO-003). Do not edit here —
  re-vendor with scripts/revendor_atp_benchmark_api.sh, which derives every
  value in this directory from the one commit it is given. Procedure:
  docs/revendor-atp-benchmark-api.md. Nothing in shipped code may read
  ../atp-platform at run time.
EOF
} > "$STAGING/PINNED.txt"

python3 "$REPO_ROOT/scripts/vendor_manifest.py" \
  --producer-commit "$NEW_PIN" --root "$STAGING" \
  --contract atp-benchmark-api --contract-version 1 ||
  die 4 "manifest generation failed"

# Checks the manifest's own claims, not merely that it parses: the pin it
# records, that it lists at least one file (a generator emitting
# {"producer_commit": <pin>, "surface": []} would otherwise pass this check),
# and that its file list is exactly the staged set.
if ! python3 - "$STAGING/manifest.json" "$NEW_PIN" "$STAGING" << 'PY'
import json
import pathlib
import sys

manifest_path, pin, root = sys.argv[1], sys.argv[2], pathlib.Path(sys.argv[3])
manifest = json.load(open(manifest_path))
if manifest.get("producer_commit") != pin:
    sys.exit(1)
surface = manifest.get("surface") or []
if not surface:
    sys.exit(1)
excluded = {"PINNED.txt", "manifest.json"}
on_disk = {
    str(p.relative_to(root))
    for p in root.rglob("*")
    if p.is_file() and p.name not in excluded
}
listed = {entry["path"] for entry in surface}
sys.exit(0 if listed == on_disk else 1)
PY
then
  die 4 "the generated manifest does not record the pin it was given, is empty, or its surface does not match the staged files"
fi

# Only now is the working copy touched, and the swap is two renames on one
# filesystem with the trap above standing behind them. Either mv failing is
# an internal failure, not a usage error — the trap restores $DST from
# $PREV if the second rename is what failed.
if [ -e "$DST" ]; then
  mv "$DST" "$PREV" || die 5 "could not move $DST aside to $PREV"
fi
mv "$STAGING" "$DST" || die 5 "could not move the staged copy into $DST"
rm -rf "$PREV"

cat >&2 << EOF
re-vendored atp-benchmark-api openapi.json at $NEW_PIN
  provenance: local checkout at $FROM, worktree HEAD verified == $NEW_PIN
  next:       uv run pytest tests/test_atp_benchmark_api_vendor.py \\
                tests/test_benchmarks.py -v
EOF
